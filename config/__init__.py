"""تنظیمات پروژه شهیدنامه."""
# ─────────────────────────────────────────────────────────────────────────────
# درایور MySQL — آماده‌سازی پیش از هر چیز
#
# این فایل __init__ بستهٔ config است و پیش از config.settings (و هر جایی که
# جنگو بخواهد به دیتابیس وصل شود — manage.py، wsgi، تست‌ها) بارگذاری می‌شود؛
# پس جای درست آماده‌سازی درایور دیتابیس همین‌جاست:
#
#   • اگر mysqlclient (درایور سریع C) نصب باشد → همان استفاده می‌شود.
#   • وگرنه PyMySQL (درایور پایتونِ خالص، بدون نیاز به کامپایلر) به‌نام
#     MySQLdb معرفی می‌شود. این برای هاست‌های اشتراکی cPanel ضروری است که
#     اجرای gcc را مسدود می‌کنند و ساخت wheel درایور C روی آن‌ها ممکن نیست
#     (خطای واقعی: «Permission denied: 'gcc'»).
#
# جنگو برای درایور MySQL حداقل نسخهٔ 1.4.3 را کنترل می‌کند؛ PyMySQL نسخهٔ
# خودش را (مثلاً 1.1.x) گزارش می‌دهد، پس طبق روش استاندارد و رایج، حداقل
# نسخهٔ مجاز برایش معرفی می‌شود.
# ─────────────────────────────────────────────────────────────────────────────
try:
    import MySQLdb  # noqa: F401  (mysqlclient — درایور C)
except ImportError:
    try:
        import pymysql
    except ImportError:
        # هیچ درایوری نصب نیست؛ جنگو خودش پیام خطای روشن می‌دهد.
        pass
    else:
        pymysql.version_info = (1, 4, 6, "final", 0)  # noqa: GL08
        pymysql.install_as_MySQLdb()
